import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtempSync,readFileSync,writeFileSync,existsSync,mkdirSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const require=createRequire(import.meta.url);
const {createInstallation,checkAdministrator,validateConnection,safeDataDirectory,pickDataDirectory,findFreePort,folderName}=require('../desktop/desktop-config.cjs');
const {exportBackup,decodeBackup,inspectBackup,restoreBackup}=require('../desktop/maintenance.cjs');
const secure={encryptString:value=>Buffer.from('os:'+value),decryptString:value=>{const text=value.toString();assert.ok(text.startsWith('os:'));return text.slice(3);}};
test('Windows fresh install, encrypted archive integrity, transactional restore and data retention',async()=>{
 const root=mkdtempSync(join(tmpdir(),'zubayd-desktop-')),data=join(root,'customer'),archive=join(root,'backup.zubayd');
 const password='isolated-admin-test-password',backupPassword='isolated-archive-test-password';
 assert.throws(()=>safeDataDirectory(join(root,'install','customer-data'),join(root,'install')),/DATA_INSIDE_INSTALLATION/);
 assert.equal(safeDataDirectory(data,join(root,'install')),data);
 assert.throws(()=>createInstallation(join(root,'bad-en'),{companyName:'x',companyNameEn:'شركة',username:'admin-test',password}),/SETUP_INPUT/);
 createInstallation(data,{companyName:'شركة العميل',companyNameEn:'Client Co',username:'admin-test',password});
 writeFileSync(join(data,'vault-key.bin'),secure.encryptString('isolated-vault-key'));
 const state=JSON.parse(readFileSync(join(data,'state.json')));
 assert.equal(state.devices.length,0);assert.equal(state.people.length,0);assert.equal(state.accounts[0].password,undefined);
 assert.ok(!readFileSync(join(data,'state.json'),'utf8').includes(password));
 assert.ok(checkAdministrator(data,'admin-test',password));assert.ok(!checkAdministrator(data,'admin-test','wrong'));
 assert.throws(()=>createInstallation(data,{companyName:'Overwrite',username:'other',password}),/DATA_EXISTS/);
 const nonempty=join(root,'not-empty');mkdirSync(nonempty);writeFileSync(join(nonempty,'keep.txt'),'retain');
 assert.throws(()=>createInstallation(nonempty,{}),/DATA_NOT_EMPTY/);
 assert.equal(validateConnection({}).host,'127.0.0.1');
 assert.throws(()=>validateConnection({host:'0.0.0.0',port:8787}),/HTTPS_REQUIRED/);
 assert.equal(validateConnection({host:'0.0.0.0',tlsCert:'cert',tlsKey:'key',serverName:'server.example.com',allowNetwork:true}).allowNetwork,true);
 await exportBackup(data,archive,backupPassword,secure);
 assert.ok(!readFileSync(archive,'utf8').includes('isolated-vault-key'));
 await assert.rejects(()=>decodeBackup(archive,'wrong-password-value'));
 assert.equal((await inspectBackup(archive,backupPassword)).companies,1);
 const envelope=JSON.parse(readFileSync(archive));envelope.ciphertext=Buffer.alloc(64).toString('base64');const bad=join(root,'tamper.zubayd');writeFileSync(bad,JSON.stringify(envelope));
 await assert.rejects(()=>decodeBackup(bad,backupPassword));
 const original=readFileSync(join(data,'state.json'),'utf8');
 writeFileSync(join(data,'state.json'),original.replace('شركة العميل','اسم معدل'));
 writeFileSync(join(data,'post-backup-only.txt'),'do not silently lose previous data');
 const decoded=await decodeBackup(archive,backupPassword),result=await restoreBackup(data,decoded,secure);
 assert.equal(readFileSync(join(data,'state.json'),'utf8'),original);
 assert.ok(existsSync(join(result.previousDirectory,'post-backup-only.txt')));
 assert.ok(!existsSync(join(data,'post-backup-only.txt')));
 assert.equal(secure.decryptString(readFileSync(join(data,'vault-key.bin'))),'isolated-vault-key');
 const malicious=await decodeBackup(archive,backupPassword);malicious.files['../escape.json']='e30=';
 await assert.rejects(()=>restoreBackup(data,malicious,secure),/BACKUP_PATH/);
 assert.equal(readFileSync(join(data,'state.json'),'utf8'),original);
});
test('auto data folder under Documents and free port',async()=>{
 const docs=mkdtempSync(join(tmpdir(),'docs-'));
 assert.equal(folderName('Magvision Co.'),'Magvision Co');
 assert.equal(pickDataDirectory(docs,'Acme').dir,join(docs,'Acme'));
 mkdirSync(join(docs,'Acme'));writeFileSync(join(docs,'Acme','other.txt'),'x');
 assert.equal(pickDataDirectory(docs,'Acme').dir,join(docs,'Acme-2'));
 const net=require('node:net');const s=net.createServer();await new Promise(r=>s.listen(0,'127.0.0.1',r));const used=s.address().port;
 assert.notEqual(await findFreePort(used),used);s.close();rmSync(docs,{recursive:true,force:true});
});
